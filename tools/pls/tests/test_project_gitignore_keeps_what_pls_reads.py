"""The project repository is shared by a team (team rollout decision N21): it keeps every file `pls` or a gate reads
on another person's machine, and leaves out only working notes that are regenerated or read by nobody else.
Checked with git itself against the template `.gitignore` that `pls init` copies."""
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve()
TEMPLATE = HERE.parents[3] / "templates" / "project" / ".gitignore"

# read by pls or by a gate on the approver's machine, or kept as audit / design evidence
KEPT = [
    "config/loans/site.json", "requirements/REQ-001-x.md", "requirements/index.md",
    "requirements/sources/2026-11-18-request.md",          # pls check p1: every REQ names a source file here
    "design/decisions/DES-001-x.md", "design/as-is/loans.md", "design/roles.json", "design/slot-ledger.json",
    "design/probes/2026-11-18-probe.md", "environments.json", "traceability.json", "tests/api/loans.json",
    "tests/results/dev-20261118-loans-http.json",          # pls coverage: the G3 evidence
    "releases/R-1/plan.json", "gates/2026-11-18-G1-120000-abc.json", "gates/profile/x.json",
    "ops/drift/x.md", "ops/onboarding/2026-11-18-summary.md", "ops/log/2026-11-18-Nam.jsonl",
    "ops/usage/s.json", "ops/kb-verify/2026-11-18-dev.md", "CLAUDE.md", ".claude/framework.lock",
]
# regenerated by pls (xref, adopt) or read by nobody else (triage notes, env-compare values)
IGNORED = ["ops/xref/loans.json", "ops/adopt/2026-11-18-dev-loans.md", "ops/triage/2026-11-18-dev-1-x.md",
           "ops/env-compare/loans.md", ".pls/connections.json", "dist/R-1-stg.zip"]


@unittest.skipUnless(shutil.which("git"), "git is needed to read the .gitignore as git does")
class ProjectGitignoreTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.r = Path(self.tmp.name)
        subprocess.run(["git", "init", "-q", str(self.r)], check=True)
        shutil.copy(TEMPLATE, self.r / ".gitignore")

    def tearDown(self):
        self.tmp.cleanup()

    def ignored(self, path: str) -> bool:
        return subprocess.run(["git", "-C", str(self.r), "check-ignore", "-q", "--no-index", path]).returncode == 0

    def test_files_pls_reads_on_another_machine_are_kept(self):
        self.assertEqual([p for p in KEPT if self.ignored(p)], [])

    def test_only_regenerated_or_private_working_notes_are_left_out(self):
        self.assertEqual([p for p in IGNORED if not self.ignored(p)], [])


if __name__ == "__main__":
    unittest.main()
