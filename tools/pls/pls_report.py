"""Operator part of a release report, written by `release-plan` from plan.json — no LLM.

`releases/<release>/diff-report.operator.md` (English) holds every technical fact of the release: target, sites
and ids, classification with reasons, order, the checks `pls` made, rollback, what happens after apply, and the
changed paths per site. The person-facing Japanese summary (`diff-report.md`) is the only part an LLM writes.
"""
from __future__ import annotations


def _paths(cls: dict) -> list[tuple[str, str]]:
    out = []
    for kind in ("data_impacting", "permission_impacting", "config_only"):
        out += [(kind.replace("_", "-"), p) for p in cls.get(kind) or []]
    return out


def operator_report(plan: dict, titles: dict[str, str]) -> str:
    rel, env, order = plan.get("release"), plan.get("env"), plan.get("sites") or []
    ps = plan.get("per_site") or {}
    sites = ", ".join(f"{s} ({ps[s].get('site_id')}, {titles.get(s, s)})" for s in order)
    total = sum((ps[s].get("changes") or 0) for s in order)
    out = [f"# {rel} — operator details", "",
           f"> Generated by `pls release-plan` from `plan.json`. The Japanese summary for the business owner is "
           f"`diff-report.md`; this file is not edited by hand.", "",
           "| Item | Value |", "|---|---|",
           f"| Target | {env}: {sites} |",
           f"| Classification | {plan.get('classification')} ({total} change(s)) |",
           f"| Order | {' → '.join(order)}" + (f" (reference cycle: {', '.join(plan['dependency_cycle'])})"
                                                if plan.get("dependency_cycle") else "") + " |",
           f"| Migration | {plan.get('migration') or 'none'} |",
           f"| Preflight | {plan.get('preflight')} |",
           f"| On failure | {plan.get('on_failure')} |",
           f"| After apply | {plan.get('post_apply_check')} |"]
    vc = plan.get("version_check") or {}
    tgt = vc.get("target") or {}
    out.append(f"| Pleasanter version | target {tgt.get('app')} (build {tgt.get('build')}, schema {tgt.get('schema')})"
               + (f"; differs from tested: {vc['differences']}" if vc.get("differences") else "; same as tested") + " |")
    out += ["", "## Checks per site", "", "| Site | Changes | Drift | Payload complete | Slots | Unverified components |",
            "|---|---|---|---|---|---|"]
    for s in order:
        ck = ps[s].get("checks") or {}
        scope = ck.get("scope") if isinstance(ck.get("scope"), dict) else {}     # "clean" when nothing is unverified
        unv = scope.get("unverified") or []
        acc = f"{len(unv)} accepted by `{scope.get('accepted_by')}`" if unv and scope.get("accepted_by") else (str(len(unv)) if unv else "none")
        out.append(f"| {s} | {ps[s].get('changes')} | {ck.get('drift_vs_last_release')} | "
                   f"{'yes' if ck.get('L-DEP-01_complete_payload') else 'NO'} | {ck.get('slot_collisions')} | {acc} |")
    out += ["", "## Changed paths", ""]
    for s in order:
        cls = ps[s].get("classification")
        rows = _paths(cls if isinstance(cls, dict) else {})
        out.append(f"### {s}" + ("" if rows else " — no change"))
        out += [f"- `{p}` — {k}" for k, p in rows]
        side = ps[s].get("side_effects") or []
        if side:
            out.append(f"- side effects: {', '.join(map(str, side))}")
        out.append("")
    out.append("Raw differences: `raw-diff-<site>.md`; rollback payloads: `rollback-<site>.json`.")
    return "\n".join(out) + "\n"
